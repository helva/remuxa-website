const menuButton = document.querySelector('.menu-toggle');
const nav = document.querySelector('.nav-links');
let currentLanguage = 'en';

function setLanguage(language) {
  currentLanguage = language === 'tr' ? 'tr' : 'en';
  const words = copy[currentLanguage];
  document.documentElement.lang = currentLanguage;
  document.title = words.title;
  document.querySelector('meta[name="description"]').content = words.description;
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const value = words[element.dataset.i18n];
    if (value !== undefined) element.textContent = value;
  });
  document.querySelectorAll('[data-i18n-html]').forEach(element => {
    const value = words[element.dataset.i18nHtml];
    if (value !== undefined) element.innerHTML = value;
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(element => {
    element.setAttribute('aria-label', words[element.dataset.i18nAria]);
  });
  document.querySelectorAll('[data-i18n-alt]').forEach(element => {
    element.setAttribute('alt', words[element.dataset.i18nAlt]);
  });
  document.querySelectorAll('[data-language]').forEach(button => {
    button.setAttribute('aria-pressed', String(button.dataset.language === currentLanguage));
    button.setAttribute('aria-label', words[button.dataset.language === 'en' ? 'switchEnglish' : 'switchTurkish']);
  });
  document.querySelector('.contact-email').href = currentLanguage === 'tr'
    ? 'mailto:destek@remuxa.com'
    : 'mailto:support@remuxa.com';
  menuButton.setAttribute('aria-label', words[menuButton.getAttribute('aria-expanded') === 'true' ? 'menuClose' : 'menuOpen']);
  localStorage.setItem('remuxa-language-v2', currentLanguage);
}

menuButton.addEventListener('click', () => {
  const open = menuButton.getAttribute('aria-expanded') === 'true';
  menuButton.setAttribute('aria-expanded', String(!open));
  menuButton.setAttribute('aria-label', copy[currentLanguage][open ? 'menuOpen' : 'menuClose']);
  nav.classList.toggle('open', !open);
});

nav.querySelectorAll('a').forEach(link => link.addEventListener('click', () => {
  nav.classList.remove('open');
  menuButton.setAttribute('aria-expanded', 'false');
  menuButton.setAttribute('aria-label', copy[currentLanguage].menuOpen);
}));

document.querySelectorAll('[data-language]').forEach(button => {
  button.addEventListener('click', () => setLanguage(button.dataset.language));
});

document.querySelector('#year').textContent = new Date().getFullYear();
setLanguage(localStorage.getItem('remuxa-language-v2') || 'tr');
